"""Write the headers the A7 IV helper (helper/readcheck.c) needs to carry the FX2 1.01 designs (FX2 port, 2026-11-25).

  work/venv/Scripts/python.exe -I -B gen_fx2_write.py

The FX2 is the A7 IV's sensor on the A7C II's platform: its designs are the A7 IV's kit (raw write buffer, sensor side, output size,
encoder side with the MP4 header heights), ported as the A7C II kit's were, and the screen step is the FX3 kit's kind (the rear screen at
3:2 and the camera's own De-Squeeze Display ratios for a 3:2 picture). Made from helper_c2/gen_c2_write.py (the A7C II: the same 0x170-byte
stored record and the same DMM layouts 0x8c / 0x8d) and helper_fx3/gen_fx3_write.py (the encoder header with the MP4 code sites and the
screen words). The write levels of readcheck.c are used as they are; only their tables and a few constants differ (build_fx2_write.sh).
This writes, into helper/, in gen_expected.py's formats:
  expected_dmm_dmmwb4688_fx2_v1.h            levels 13/14: the four DMM words, their unit records and the parent records
  expected_sites_ogsq_fx2_v1.h               levels 5/6: 13 sensor/record sites and the changed bytes of the 0x170-byte stored record
  expected_words_outsz2560_fx2_v1.h          levels 16/17: the output-size word and its guards
  expected_words_lcd32dsq_fx2_v1.h           levels 16/17 (S16/S17): the rear screen at 3:2, the frame rectangles, the de-squeeze words
  expected_mp_ogfile2560_hs_s_fx2_v2.h       levels 19/20: encoder-side sites in av-cam.bin and libmpr.so, with the two MP4 header heights
  expected_mp_ogfile2560_hs_s_fx2_v1.h       levels 19/20 (N19): the same without the heights (--no-meta)
Every stock byte is compared with the 1.01 files here. gen_expected.py is not used: its checks name A7 IV addresses.
"""
import hashlib
import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "helper"
ROOT = HERE.parents[2]
EX = ROOT / "work/extracted/fx2_101/0700_part_image/dev"
DES = ROOT / "modding/designs"
sys.path.insert(0, str(ROOT / "build"))
import parse_dmmcfg  # noqa: E402
import build_ogfile  # noqa: E402

BASE = 0x108000
IMAGE = (EX / "nflasha8/cpapp-b.bin").read_bytes()
IMAGE_END = BASE + len(IMAGE)
OB = build_ogfile.OTHER_BUILDS["fx2_101"]
DESC, DSIZE, UNIT, CLIP, COMB = OB["desc"], OB["dsize"], OB["unit"], OB["clip"], OB["comb"]
PROFILE_END = max(a + n * 0x100 for a, n in OB["profiles"])
REC = 0x170
DATA_LO = 0xD80000                                 # every cpapp-b.bin table site of the sensor design lies above this (records 0xdf9958 on)
GROUPS = (0x8C, 0x8D)                              # steer, grow: the A7C II's numbers (build_dmm_sites.py fx2_101)
hx = lambda b: ", ".join("0x%02x" % x for x in b)
HEAD = "/* Generated by helper_fx2/gen_fx2_write.py from modding/designs/%s.json (FX2 1.01). Do not edit. */"


def design(name):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d.get("build") == "fx2_101", name
    return d


def sites_header(name="ogsq_fx2_v1"):
    d = design(name)
    assert d["artifact_sha256"] == hashlib.sha256(IMAGE).hexdigest()
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    out = [HEAD % name, "/* %d sites, %d bytes. Stock bytes were compared with cpapp-b.bin %s. */" % (len(sites), sum(len(o) for _, o, _ in sites), d["artifact_sha256"][:16])]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and IMAGE[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and DATA_LO <= lo and hi <= IMAGE_END, "span outside the image's tables"
        for tag, data in (("old", old), ("new", new)):
            out.append("static const u8 site%d_%s[%d] = { %s };" % (k, tag, len(data), hx(data)))
        rows.append("    { 0x%x, %d, site%d_old, site%d_new, 0, 0 }," % (a, len(old), k, k))
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"
    assert d["record_size"] == REC and len(sites) == 13
    r_stock, r_new = bytes.fromhex(d["stored_record"]["stock"]), bytes.fromhex(d["stored_record"]["design"])
    offs = [k for k in range(REC) if r_stock[k] != r_new[k]]
    assert len(r_stock) == len(r_new) == REC and r_stock[6] == r_stock[7] == 1 and 2 < len(offs) <= 128
    # the squeeze designs change the vertical sampling ratio (+6/+7 = 27/32); the band test (fhband_fx2_v1, second kit) keeps it stock
    assert (offs[:2] == [6, 7]) == bool(d.get("stored_record_extra")), "the record's +6/+7 bytes do not match the design's stored_record_extra"
    out += ["static const unsigned short rec_offs[%d] = { %s };" % (len(offs), ", ".join("0x%x" % k for k in offs)),
            "static const u8 rec_stock[%d] = { %s };" % (len(offs), hx(bytes(r_stock[k] for k in offs))),
            "static const u8 rec_new[%d] = { %s };" % (len(offs), hx(bytes(r_new[k] for k in offs))),
            "#define REC_BYTES %d" % len(offs),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + 1),
            "#define MODE_ID %sU" % d["mode_id"], '#define MODE_TEXT "%s"' % d["mode_id"],
            "/* offs: null for a site whose `length` bytes all change; else the offsets, inside `length` bytes, of the noffs bytes that change. */",
            "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
            "static const struct cp_site cp_sites[] = {"] + rows + ["};"]
    (OUT / f"expected_sites_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(offs), d["mode_id"]


def dmm_header(name="dmmwb4688_fx2_v1"):
    """gen_c2_write.dmm_header with this build's DmmCfg.bin, RAM copy and groups (0x8c steer, 0x8d grow, as on the A7C II)."""
    design_ = design(name)
    cfg = parse_dmmcfg.Config(parse_dmmcfg.find_file("fx2_101"), "fx2_101")
    ram = lambda u: cfg.ram("unit_records", u["seq"] * 0x14)
    by_ram = {ram(u): u for g in cfg.groups for u in g["units"]}
    sites, recs = [], []
    for s in design_["sites"]:
        a, old, new = int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])
        rec = next(r for r in by_ram if r <= a < r + 0x14)
        u, off = by_ram[rec], a - rec
        assert len(old) == len(new) == 4 and old != new and off in (8, 12) and (a & 63) <= 60
        assert u["key"] == 0x57F and u["group"]["gid"] in GROUPS and cfg.data[u["at"] + off:u["at"] + off + 4] == old
        sites.append((a, old, new))
        recs.append((rec, off, cfg.data[u["at"]:u["at"] + 0x14]))
    new_size = design_["summary"]["unit_size"]
    assert len(sites) == 4 and sorted(r for r, _, _ in recs) == sorted({r for r, _, _ in recs})
    assert [new for a, old, new in sites if old == (27864320).to_bytes(4, "little")] == [new_size.to_bytes(4, "little")] * 2
    parents = [(ram(u), cfg.data[u["at"]:u["at"] + 0x14]) for u in cfg.units_by_key[0x6FA]]
    assert len(parents) == 4 and all(u["size"] >= 2 * new_size for u in cfg.units_by_key[0x6FA]) and new_size % 128 == 0
    spare = sorted({int.from_bytes(new, "little") for a, old, new in sites if old == (0x57F).to_bytes(4, "little")})
    assert len(spare) == 1 and spare[0] not in cfg.units_by_key and all(spare[0] not in r["keys"] for r in cfg.ids)
    busy = [0x57F, 0x634, 0x635, spare[0]]
    assert {u["key"] for g in cfg.groups if g["gid"] in GROUPS for u in g["units"]} == {0x57F, 0x634, 0x635}
    out = [HEAD % name,
           "/* The memory manager's RAM copy of its unit records (cpapp-b.bin 1.01, %#x on): %d words in %d records. */" % (cfg.ram("unit_records", 0), len(sites), len(recs)),
           '#define DMM_DESIGN "%s"' % name,
           "/* the new unit size, and how many units of it must fit the parent */",
           "static const u32 dmm_fit[2] = { %dU, 2U };" % new_size,
           "struct dmm_site { u32 address; u8 stock[4]; u8 changed[4]; };",
           "static const struct dmm_site dmm_sites[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(old), hx(new)) for a, old, new in sites]
    out += ["};", "/* the record each site lies in, as in the file: every byte but the site's four (from site_off) must equal these */",
            "struct dmm_rec { u32 address; u32 site_off; u8 file[20]; };", "static const struct dmm_rec dmm_recs[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (r, off, hx(b)) for r, off, b in recs]
    out += ["};", "/* the records of the parent unit (key 0x6fa): all 20 bytes must equal the file's, and the size must hold two units of the new size */",
            "static const struct dmm_rec dmm_parents[] = {"]
    out += ["    { 0x%x, 0xff, { %s } }," % (r, hx(b)) for r, b in parents]
    out += ["};", "/* a unit object of one of these keys in a division still in force: nothing is written */",
            "static const u32 dmm_busy_keys[] = { %s };" % ", ".join("0x%x" % k for k in busy)]
    (OUT / f"expected_dmm_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), [hex(r) for r, _ in parents]


# Where a words design may have a site, and where only a guard (FX2 addresses; build/build_ram_words_fx2.py, build/build_lcd_fx2.py)
SIZE_TABLE = (0x18F60B0, 0x18F60B0 + 0x80)
WORD_REGIONS = {"outsz2560_fx2_v1": ((SIZE_TABLE,), ())}
LCD_REGIONS = HERE / "lcd_regions_fx2.json"         # written from the screen design's builder (site regions, guard-only regions)


def words_header(name):
    d = design(name)
    assert d["kind"] == "ram_words"
    sites = [(int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])) for s in d["sites"]]
    guards = [(int(g["ram_address"], 16), bytes.fromhex(g["bytes"])) for g in d["guards"]]
    if name in WORD_REGIONS:
        site_regions, guard_only = WORD_REGIONS[name]
    else:
        r = json.loads(LCD_REGIONS.read_text(encoding="utf8"))[name]
        site_regions = tuple((int(a, 16), int(b, 16)) for a, b in r["sites"])
        guard_only = tuple((int(a, 16), int(b, 16)) for a, b in r["guards"])
    within = lambda a, n, regions: any(lo <= a and a + n <= hi for lo, hi in regions)
    assert sites and all(len(o) == len(n) == 4 and o != n and a % 4 == 0 and within(a, 4, site_regions) for a, o, n in sites), name
    assert guards and all(0 < len(b) <= 16 and within(a, len(b), site_regions + guard_only) for a, b in guards), name
    for a, o, _ in sites:                                  # words inside the loaded image: the file's bytes
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + 4] == o
    for a, b in guards:
        if BASE <= a < IMAGE_END:
            assert IMAGE[a - BASE:a - BASE + len(b)] == b
    assert not any(a < sa + 4 and sa < a + len(b) for a, b in guards for sa, _, _ in sites), "a guard overlaps a site"
    out = [HEAD % name, "/* Words of the coprocessor's RAM tables (cpapp-b.bin 1.01): %d site(s), %d guard(s). */" % (len(sites), len(guards)),
           '#define WORDS_DESIGN "%s"' % name, "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };", "static const struct ram_word ram_words[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(o), hx(n)) for a, o, n in sites]
    out += ["};", "/* bytes beside the sites that must be as listed before anything is written */",
            "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };", "static const struct ram_guard ram_guards[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (a, len(b), hx(b.ljust(16, b"\0"))) for a, b in guards]
    out += ["};"]
    (OUT / f"expected_words_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(guards)


def mp_header(name):
    """helper_fx3/gen_fx3_write.mp_header with this build's tables: a code site is allowed only in libmpr.so and only where the design names
    it in libmpr_code_guards, with the instructions around it as guards (build_ogfile.py checks them by disassembly)."""
    d = design(name)
    av, lm = (EX / "nflasha3/av-cam.bin").read_bytes(), (EX / "nflasha15/lib/libmpr.so").read_bytes()
    assert d["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    code_ok = {int(g["site"], 16): g["guards"] for g in d.get("libmpr_code_guards", [])}
    assert all(not p["code"] or (p["binary"] == "libmpr.so" and int(p["file_off"], 16) in code_ok) for p in d["patches"]), \
        "not a data-only encoder-side design (a code site must be in libmpr.so and named in libmpr_code_guards)"
    tabs = {"av-cam.bin": [], "libmpr.so": []}
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        data = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and data[off:off + len(old)] == old
        tabs[p["binary"]].append((off, 1, old, new))
    # guards, as gen_expected.py --mp: the 4K row of the unit-type table, clip-format row 5, each changed descriptor's profile key
    g_av = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    for x in d["descriptors"]:
        o = DESC + x["descriptor"] * DSIZE + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        g_av.append((o, av[o:o + 4]))
    g_lm = [(0, lm[:16])]
    for off, _, old, new in tabs["libmpr.so"]:
        if off in code_ok:                                       # a named code site: its guards are the instructions the design lists
            for g in code_ok[off]:
                a, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
                assert lm[a:a + len(b)] == b and len(b) <= 16
                g_lm.append((a, b))
            continue
        assert (off - 6 - COMB) % 0x18 == 0 and struct.unpack_from("<H", lm, off - 2)[0] == 3840
        g_lm.append((off - 6, lm[off - 6:off]))
    for binary, guards in (("av-cam.bin", g_av), ("libmpr.so", g_lm)):
        sites = tabs[binary]
        assert not any(a < s + len(o) and s < a + len(b) for a, b in guards for s, _, o, _ in sites), "a guard overlaps a site"
        tabs[binary] = sorted(sites + [(a, 0, b, b"") for a, b in guards])
        assert all(tabs[binary][k][0] + len(tabs[binary][k][2]) <= tabs[binary][k + 1][0] for k in range(len(tabs[binary]) - 1)), "entries overlap"
    first = tabs["av-cam.bin"][0][0] & ~0xFFF
    last = max(a + len(o) for a, _, o, _ in tabs["av-cam.bin"])
    span = ((last - first) + 0xFFF) & ~0xFFF
    assert (CLIP & ~0xFFF) <= first and first + span <= ((PROFILE_END + 0xFFF) & ~0xFFF), "an av-cam.bin site lies outside the pages of its tables"
    phoff, phentsize, phnum = struct.unpack_from("<Q", lm, 0x20)[0], *struct.unpack_from("<HH", lm, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lm, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lm, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0 and max(a + len(o) for a, _, o, _ in tabs["libmpr.so"]) <= load0[5], "a libmpr.so site lies outside the first segment"
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [HEAD % name,
           "/* av-cam.bin %s..., libmpr.so %s... (1.01). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */"
           % (d["artifact_sha256"]["av-cam.bin"][:16], d["artifact_sha256"]["libmpr.so"][:16]),
           '#define MP_DESIGN "%s"' % name,
           "#define MP_AV_FIRST 0x%xUL                 /* file offset of the first page read of av-cam.bin */" % first,
           "#define MP_AV_BYTES 0x%xUL                  /* whole pages: every entry of mp_av lies inside */" % span,
           "struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };"]
    longest = max(len(tabs["av-cam.bin"]), len(tabs["libmpr.so"]))
    if longest > 96:
        out.insert(-1, "#define MP_MAX %d                          /* room for the entries of the longer table (levels 19 and 20) */" % ((longest + 31) & ~31))
    for binary, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, binary))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in tabs[binary]]
        out.append("};")
    (OUT / f"expected_mp_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return {b: (sum(1 for e in t if e[1] == 1), sum(1 for e in t if e[1] == 0)) for b, t in tabs.items()}, hex(first), hex(span)


if __name__ == "__main__":
    print("dmm header dmmwb4688_fx2_v1", dmm_header())
    print("sites header ogsq_fx2_v1", sites_header())
    print("sites header fhband_fx2_v1 (second kit, test 1)", sites_header("fhband_fx2_v1"))
    print("words header outsz2560_fx2_v1", words_header("outsz2560_fx2_v1"))
    if (DES / "lcd32dsq_fx2_v1.json").exists():
        print("words header lcd32dsq_fx2_v1", words_header("lcd32dsq_fx2_v1"))
    for n in ("ogfile2560_hs_s_fx2_v2", "ogfile2560_hs_s_fx2_v1"):
        print("mp header", n, mp_header(n))
